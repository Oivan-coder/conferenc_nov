import fs from 'node:fs';
import path from 'node:path';

const projectRoot = process.cwd();
const cssRoot = path.join(projectRoot, 'css');
const mainPath = path.join(cssRoot, 'main.css');
const outputPath = path.join(cssRoot, 'public-bundle.css');

const rewriteUrls = (css, sourcePath) => css.replace(
    /url\((['"]?)(?!data:|https?:|\/|#)([^)'"?#]+)(?:\?[^)'"#]*)?\1\)/g,
    (_match, quote, assetPath) => {
        const absoluteAsset = path.resolve(path.dirname(sourcePath), assetPath);
        const relativeAsset = path.relative(path.dirname(outputPath), absoluteAsset).split(path.sep).join('/');
        const normalized = relativeAsset.startsWith('.') ? relativeAsset : `./${relativeAsset}`;
        return `url(${quote}${normalized}${quote})`;
    }
);

const mainSource = fs.readFileSync(mainPath, 'utf8');
const importPattern = /@import\s+url\((['"]?)([^)'"?#]+)(?:\?[^)'"#]*)?\1\)\s*;[^\n]*\n?/g;
const importedFiles = [];

for (const match of mainSource.matchAll(importPattern)) {
    importedFiles.push(path.resolve(cssRoot, match[2]));
}

const blocks = importedFiles.map((filePath) => {
    const label = path.relative(projectRoot, filePath).split(path.sep).join('/');
    const source = fs.readFileSync(filePath, 'utf8');
    return `/* bundled: ${label} */\n${rewriteUrls(source, filePath).trim()}\n`;
});

const mainWithoutImports = mainSource.replace(importPattern, '');
blocks.push(`/* bundled: css/main.css */\n${rewriteUrls(mainWithoutImports, mainPath).trim()}\n`);

const polishPath = path.join(cssRoot, 'sections', 'site-polish.css');
blocks.push(`/* bundled: css/sections/site-polish.css */\n${rewriteUrls(fs.readFileSync(polishPath, 'utf8'), polishPath).trim()}\n`);

const homeCinematicPath = path.join(cssRoot, 'sections', 'home-cinematic.css');
blocks.push(`/* bundled: css/sections/home-cinematic.css */\n${rewriteUrls(fs.readFileSync(homeCinematicPath, 'utf8'), homeCinematicPath).trim()}\n`);

const output = `/* Generated by scripts/build-public-css.mjs. Do not edit directly. */\n\n${blocks.join('\n')}`;
fs.writeFileSync(outputPath, `${output.trim()}\n`, 'utf8');

console.log(`Built ${path.relative(projectRoot, outputPath)} (${fs.statSync(outputPath).size} bytes)`);
